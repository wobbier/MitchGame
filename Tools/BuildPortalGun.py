#!/usr/bin/env python3
"""Build the portal demo's camera-mounted gun and a short, original synth firing sound."""
import json
import math
from pathlib import Path
import random
import struct
import wave

ROOT = Path(__file__).resolve().parents[1]
WHITE = [0.84, 0.88, 0.91]
DARK = [0.035, 0.045, 0.06]
BLUE = [0.02, 0.55, 1.0]


def part(name, position=(0, 0, 0), scale=(1, 1, 1), mesh=None,
         color=DARK, rotation=(0, 0, 0), glow=0, children=None):
    components = [{"Type": "Transform", "Position": list(position),
                   "Rotation": list(rotation), "Scale": list(scale)}]
    if mesh:
        components.append({"Type": "Mesh", "MeshType": mesh, "CastShadows": False,
                           "Material": {"Type": "StandardMaterial", "DiffuseColor": color,
                                        "Metallic": 0.45, "Roughness": 0.28,
                                        "EmissiveColor": color, "EmissiveIntensity": glow}})
    return {"Name": name, "Components": components, "Children": children or []}


def lathe_asset(name, profile, first=0, last=360, steps=64):
    """Smooth, code-native curved armour and machined rings; Z is the barrel axis."""
    folder = ROOT / "Assets/Models/PortalGun"
    folder.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by Tools/BuildPortalGun.py"]
    for j, (z, radius) in enumerate(profile):
        before, after = profile[max(0, j - 1)], profile[min(len(profile) - 1, j + 1)]
        dz, dr = after[0] - before[0], after[1] - before[1]
        length = math.hypot(dz, dr) or 1
        for i in range(steps + 1):
            angle = math.radians(first + (last - first) * i / steps)
            c, v = math.cos(angle), math.sin(angle)
            lines.append(f"v {radius*c:.7f} {radius*v:.7f} {z:.7f}")
            lines.append(f"vn {dz*c/length:.7f} {dz*v/length:.7f} {-dr/length:.7f}")
    for j in range(len(profile) - 1):
        for i in range(steps):
            a = j * (steps + 1) + i + 1
            ids = (a, a+1, a+steps+2, a+steps+1)
            lines.append("f " + " ".join(f"{k}//{k}" for k in ids))
    (folder / (name + ".obj")).write_text("\n".join(lines) + "\n")
    return f"Assets/Models/PortalGun/{name}.obj"


def model_part(name, path, position=(0, 0, 0), scale=(1, 1, 1), color=WHITE, glow=0):
    result = part(name, position, scale, "Model", color, glow=glow)
    result["Components"].append({"Type": "Model", "ModelPath": path})
    return result


def build():
    armour = [(-0.17, 0.024), (-0.15, 0.06), (-0.11, 0.086), (-0.04, 0.09),
              (0.06, 0.08), (0.13, 0.055), (0.14, 0.05)]
    shell_right = lathe_asset("ShellRight", armour, -65, 65)
    shell_left = lathe_asset("ShellLeft", armour, 115, 245)
    ring_profile = [(0.012*math.sin(i*math.tau/16), 1+0.10*math.cos(i*math.tau/16)) for i in range(17)]
    ring = lathe_asset("ReactorRing", ring_profile)
    parts = [
        part("Gun Chassis", (0, 0, 0.035), (0.075, 0.18, 0.07), "Cylinder", rotation=(90, 0, 0)),
        model_part("Gun Shell Left", shell_left),
        model_part("Gun Shell Right", shell_right),
        part("Gun Back Cap", (0, 0, -0.13), (0.064, 0.06, 0.045), "Sphere", DARK),
        part("Gun Grip", (0, -0.09, -0.07), (0.035, 0.08, 0.042), "Cube", DARK, (-18, 0, 0)),
        part("Gun Core", (0, 0.055, -0.015), (0.025, 0.028, 0.11), "Sphere", BLUE, glow=2),
        part("Gun Rail Left", (-0.095, 0.012, 0.015), (0.008, 0.012, 0.11), "Cube", BLUE, glow=2),
        part("Gun Rail Right", (0.095, 0.012, 0.015), (0.008, 0.012, 0.11), "Cube", BLUE, glow=2),
        part("Gun Barrel", (0, 0, 0.12), children=[
            part("Gun Sleeve", scale=(0.064, 0.085, 0.064), mesh="Cylinder", rotation=(90, 0, 0)),
            part("Gun Muzzle", (0, 0, 0.086), (0.045, 0.012, 0.045), "Cylinder", BLUE, (90, 0, 0), 3),
        ]),
        part("Gun Turbine", (0, 0, 0.17), children=[
            model_part("Gun Energy Halo", ring, scale=(0.087, 0.087, 0.6), color=BLUE, glow=2),
            *[part("Gun Turbine Blade " + str(i),
                   (math.cos(i*math.tau/9)*0.077, math.sin(i*math.tau/9)*0.077, 0),
                   (0.008, 0.019, 0.014), "Cube", [0.36, 0.22, 0.08], (0, 0, i*40+25)) for i in range(9)],
        ]),
        part("Gun Rotor", (0, 0, 0.08), children=[
            model_part("Gun Containment Ring", ring, scale=(0.096, 0.096, 1.0), color=[0.22, 0.25, 0.3]),
            *[part("Gun Rotor Lug " + str(i),
                 (math.cos(i * math.tau / 6) * 0.085, math.sin(i * math.tau / 6) * 0.085, 0),
                 (0.013, 0.022, 0.025), "Cube", WHITE, (0, 0, i * 60)) for i in range(6)]
        ]),
        part("Gun Flash", (0, 0, 0.36), (0.0001,) * 3, "Sphere", BLUE, glow=9),
        part("Gun Pulse Light", (0, 0.08, 0.3)),
    ]
    parts[-1]["Components"].append({"Type": "Light", "LightType": "Point", "Color": BLUE,
                                    "Intensity": 0, "Range": 2, "CastShadows": False})
    for i in range(5):
        parts.append(part("Gun Vent " + str(i), (0.086-i*0.001, 0, -0.10+i*0.027),
                          (0.006, 0.026, 0.003), "Cube", DARK, (0, -6, 0)))
    for i in range(3):
        angle = i * math.tau / 3
        parts.append(part("Gun Claw " + str(i), (math.cos(angle) * 0.09, math.sin(angle) * 0.09, 0.24),
                          rotation=(0, 0, i * 120), children=[
                              part("Gun Claw Arm " + str(i), (0, 0, -0.01), (0.012, 0.017, 0.095), "Cube", [0.16, 0.19, 0.23], (0, -13, 0)),
                              part("Gun Claw Hinge " + str(i), (0, 0, -0.055), (0.025, 0.026, 0.025), "Sphere", WHITE),
                              part("Gun Claw Light " + str(i), (0, 0.019, 0.012), (0.004, 0.004, 0.056), "Cube", BLUE, glow=3),
                              part("Gun Claw Tip " + str(i), (-0.018, 0, 0.074), (0.018, 0.016, 0.032), "Cube", DARK, (0, -30, 0)),
                          ]))
    gun = part("Portal Gun", (0.24, -0.23, 0.48), children=parts)
    gun["Components"].append({"Type": "ScriptComponent", "ScriptName": "PortalGun", "ScriptFields": "{}"})
    (ROOT / "Assets/Prefabs/Portals/PortalGun.prefab").write_text(json.dumps(gun, indent=4) + "\n")

    # A bass transient with a descending electronic chirp and a short mechanical noise tail.
    folder = ROOT / "Assets/Sounds/Portals"
    folder.mkdir(exist_ok=True)
    rng = random.Random(7)
    rate = 44100
    samples = []
    phase = 0
    for i in range(int(rate * 0.32)):
        t = i / rate
        phase += math.tau * (70 + 1350 * math.exp(-t * 32)) / rate
        attack = min(1, t / 0.002)
        tone = math.sin(phase) * math.exp(-t * 17)
        bass = math.sin(math.tau * 85 * t) * math.exp(-t * 26)
        noise = rng.uniform(-1, 1) * math.exp(-t * 45)
        value = math.tanh((tone * 0.55 + bass * 0.55 + noise * 0.28) * attack)
        samples.append(struct.pack('<h', int(value * 28000)))
    with wave.open(str(folder / "Pulse.wav"), 'wb') as clip:
        clip.setparams((1, 2, rate, 0, 'NONE', 'not compressed'))
        clip.writeframes(b''.join(samples))


if __name__ == '__main__':
    build()

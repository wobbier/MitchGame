#!/usr/bin/env python3
"""Small, deterministic asset helpers for BuildConcertTest.py (Python 3 only).

The crowd uses static posed Synty Prototype meshes, normalized to metres. These
share opaque StandardMaterial geometry for the engine's automatic instancing.
The singer uses the installed Office Pack rig and a fixed microphone pose.
"""
import copy
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Assets/Models/ConcertTest"
ATLAS = "Assets/Models/Synty/OfficePack/Textures/PolygonOffice_Texture_01_A.png"


def _write(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def standard(color=(1, 1, 1), roughness=0.8):
    return dict(Type="StandardMaterial", DiffuseColor=list(color),
                Roughness=roughness, Metallic=0, EmissiveIntensity=0)


def build_crowd_assets():
    """Return Model components keyed idle_male/female and handsup_male/female.

    Deep-copy a component before changing its Parts[*].Material palette. The
    returned Parts paths match Assimp's OBJ object/mesh naming, checked against
    the same Assimp library and postprocess flags used by ModelResource.
    """
    OUTPUT.mkdir(parents=True, exist_ok=True)
    result = {}
    sources = []
    for pose in ("idle", "handsup"):
        for gender in ("male", "female"):
            key = f"{pose}_{gender}"
            source = ROOT / f"Assets/Prototyping/OBJ/SM_Pawn_{pose.capitalize()}_{gender.capitalize()}_01.obj"
            name = f"Crowd_{key}"
            path = OUTPUT / f"{name}.obj"
            lines = ["# Derived from " + source.relative_to(ROOT).as_posix(),
                     "# Synty POLYGON Prototype Pack; original asset remains in Assets/Prototyping.",
                     "# Metres, sole at y=0. Generated by Tools/ConcertAssets.py.", "o " + name]
            data = source.read_text().splitlines()
            sole = min(float(line.split()[2]) for line in data if line.startswith("v "))
            for line in data:
                if line.startswith("v "):
                    x, y, z = map(float, line.split()[1:4])
                    lines.append(f"v {x * .01:.7f} {(y - sole) * .01:.7f} {z * .01:.7f}")
                elif line.startswith(("vt ", "vn ", "f ")):
                    lines.append(line)
            _write(path, "\n".join(lines) + "\n")
            _write(Path(str(path) + ".meta"), json.dumps(dict(
                FileType="obj", GUID=hashlib.sha256(path.relative_to(ROOT).as_posix().encode()).hexdigest()[:16],
                ConvertUnits=False), indent=4, sort_keys=True) + "\n")
            relative = path.relative_to(ROOT).as_posix()
            # Assimp's raw OBJ importer supplies the object name on the mesh;
            # its assbin exporter drops that name. Support both representations
            # so cached imports retain the explicit material and shadow setting.
            parts = {f"{path.name}#0/{name}#0/@{mesh_name}#0": dict(
                     Type="Mesh", MeshType="Model", CastShadows=True, Material=standard())
                     for mesh_name in ("", name)}
            result[key] = dict(Type="Model", ModelPath=relative, Compact=True, BakedImportScale=1,
                                 Parts=parts)
            sources.append(source.relative_to(ROOT).as_posix())
    _write(OUTPUT / "README.md", "# Concert crowd meshes\n\n"
           "Generated by `python3 Tools/ConcertAssets.py` from the installed Synty "
           "POLYGON Prototype Pack. The source assets and their material listing "
           "remain in `Assets/Prototyping/`; these files normalize centimetres to "
           "metres, place the soles at y=0, and name each OBJ object.\n\n"
           "Source files:\n\n" + "".join(f"- `{source}`\n" for source in sources) +
           "\nSource material listing: `Assets/Prototyping/MaterialList_PolygonPrototype.txt`. "
           "No separate license file was supplied in that directory. These derived "
           "meshes retain the source pack's ownership and licensing.\n")
    return result


def _add(a, b):
    return [x + y for x, y in zip(a, b)]


def _sub(a, b):
    return [x - y for x, y in zip(a, b)]


def _scale(a, s):
    return [x * s for x in a]


def _length(a):
    return math.sqrt(sum(x * x for x in a))


def _norm(a):
    return _scale(a, 1 / (_length(a) or 1))


def _mul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return [aw*bx + ax*bw + ay*bz - az*by, aw*by - ax*bz + ay*bw + az*bx,
            aw*bz + ax*by - ay*bx + az*bw, aw*bw - ax*bx - ay*by - az*bz]


def _conj(q):
    return [-q[0], -q[1], -q[2], q[3]]


def _rotate(q, v):
    return _mul(_mul(q, list(v) + [0]), _conj(q))[:3]


def _arc(a, b):
    a, b = _norm(a), _norm(b)
    dot = sum(x*y for x, y in zip(a, b))
    if dot < -.9999:
        return [0, 0, 1, 0] if abs(a[1]) > .9 else [0, 1, 0, 0]
    return _norm([a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2],
                  a[0]*b[1] - a[1]*b[0], 1 + dot])


def _pose(nodes, goals):
    """Two-bone arm IK in model space, using the stored Office rig bind pose."""
    nodes = copy.deepcopy(nodes)
    index = {n["name"]: i for i, n in enumerate(nodes)}
    rest = []
    for n in nodes:
        p, q = rest[n["parent"]] if n["parent"] >= 0 else ([0, 0, 0], [0, 0, 0, 1])
        rest.append((_add(p, _rotate(q, n["pos"])), _mul(q, n["rot"])))
    pending = {}
    for side, target, pole in goals:
        chain = (f"UpperArm_{side}", f"lowerarm_{side.lower()}", f"Hand_{side}")
        pending[chain[0]] = (chain, target, pole)
    world = []
    for i, n in enumerate(nodes):
        p, q = world[n["parent"]] if n["parent"] >= 0 else ([0, 0, 0], [0, 0, 0, 1])
        pos, rot = _add(p, _rotate(q, n["pos"])), _mul(q, n["rot"])
        if n["name"] in pending:
            spec = pending[n["name"]]
            if len(spec) == 3:
                (upper, lower, end), target, pole = spec
                l1 = _length(_sub(rest[index[lower]][0], rest[index[upper]][0]))
                l2 = _length(_sub(rest[index[end]][0], rest[index[lower]][0]))
                direction = _sub(target, pos)
                d, axis = min(_length(direction), (l1 + l2)*.999), _norm(direction)
                a = (l1*l1 - l2*l2 + d*d)/(2*d)
                h = math.sqrt(max(l1*l1 - a*a, 0))
                across = _norm(_sub(pole, _scale(axis, sum(x*y for x, y in zip(pole, axis)))))
                goal = _add(pos, _add(_scale(axis, a), _scale(across, h)))
                joint = lower
                pending[lower] = (end, target)
            else:
                joint, goal = spec
            offset = _rotate(_conj(rest[i][1]), _sub(rest[index[joint]][0], rest[i][0]))
            rot = _mul(_arc(_rotate(rot, offset), _sub(goal, pos)), rot)
            n["rot"] = [round(x, 7) for x in _mul(_conj(q), rot)]
        world.append((pos, rot))
    return nodes


def _transform(position=(0, 0, 0), rotation=(0, 0, 0, 1), scale=(1, 1, 1)):
    return dict(Type="Transform", Position=list(position), Rotation=list(rotation), Scale=list(scale))


def add_performer(scene, name, position, facing=145, parent=None):
    """Create the singer + mic; return the root entity dict.

    `facing` is the compass direction of the face: 0=+Z, 90=+X, 180=-Z.
    `scene.entity(name, components, parent=None)` must return a GUID-bearing dict.
    The root contains one compact skinned Model and a complete fixed bone pose.
    """
    key = "SK_Chr_Developer_Female_01"
    rig = json.loads((ROOT / "Tools/LaunchNightRigs.json").read_text())[key]
    nodes = _pose(rig["Nodes"], [("R", (-.11, 1.44, -.29), (-.8, .25, -.6)),
                                ("L", (.28, .89, -.12), (.7, -.4, -.5))])
    material = standard(roughness=.72)
    material["Textures"] = {"Diffuse": dict(Path=ATLAS, RenderMode="Opaque")}
    paths, overrides = [], {}
    for n in nodes:
        path = (paths[n["parent"]] if n["parent"] >= 0 else "RootNode#0") + "/" + n["name"] + "#0"
        paths.append(path)
        overrides[path] = _transform(n["pos"], n["rot"], n["scale"])
    # Older Office assbins have an empty mesh name; a fresh current Assimp
    # import preserves the FBX name. Keep both overrides so either cook works.
    parts = {f"RootNode#0/{key}#0/@{mesh_name}#0": dict(Type="Mesh", MeshType="Model",
             CastShadows=True, Material=copy.deepcopy(material)) for mesh_name in ("", key)}
    model = dict(Type="Model", ModelPath=rig["ModelPath"], Compact=True,
                 BakedImportScale=rig["BakedImportScale"], Nodes=overrides, Parts=parts)
    h = math.radians(facing + 180)/2
    root = scene.entity(name, [_transform(position, (0, math.sin(h), 0, math.cos(h))), model], parent)
    # The fixed pose grips the handle just beneath the grille at the mouth.
    tip, base = (-.045, 1.50, -.19), (-.125, 1.40, -.31)
    middle, axis = _scale(_add(tip, base), .5), _sub(tip, base)
    scene.entity(name + " microphone handle", [_transform(middle, _arc((0, 1, 0), axis),
        (.018, _length(axis)/2, .018)), dict(Type="Mesh", MeshType="Cylinder",
            CastShadows=True, Material=standard((.045, .05, .055), .4))], root)
    scene.entity(name + " microphone grille", [_transform(tip, scale=(.032, .038, .032)),
        dict(Type="Mesh", MeshType="Sphere", CastShadows=True,
             Material=standard((.3, .32, .34), .75))], root)
    return root


if __name__ == "__main__":
    for key, component in build_crowd_assets().items():
        print(key, component["ModelPath"])
